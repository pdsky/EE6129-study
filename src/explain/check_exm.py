def eb(A, M):
    b = 1.0
    for k in range(1, M + 1): b = A * b / (k + A * b)
    return b
def erl(M, p):
    lo, hi = 0.0, 2.0 * M
    for _ in range(200):
        mid = (lo + hi) / 2
        lo, hi = (lo, mid) if eb(mid, M) > p else (mid, hi)
    return lo
