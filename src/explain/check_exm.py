class P(HTMLParser):
    def __init__(s, key):
        super().__init__(convert_charrefs=True); s.key = key; s.stack = []; s.bad = []
    def handle_starttag(s, tag, attrs):
        a = dict(attrs); cls = a.get('class')
        if tag not in ALLOWED: s.bad.append(f'tag {tag}')
        else:
            if ALLOWED[tag] and cls not in ALLOWED[tag]: s.bad.append(f'{tag} class {cls}')
            if not ALLOWED[tag] and cls: s.bad.append(f'{tag} has class {cls}')
            for k in a:
                if k not in ('class', 'lang'): s.bad.append(f'attr {k}')
            if 'lang' in a and not (tag == 'div' and cls == 'tmpl' and a['lang'] == 'en'): s.bad.append('lang misuse')
            if tag == 'div' and cls == 'tmpl' and a.get('lang') != 'en': s.bad.append('tmpl without lang=en')
            par = s.stack[-1] if s.stack else None
            if tag == 'span' and par != ('h4', None): s.bad.append('span.st outside h4')
            if tag == 'table' and par != ('div', 'tw'): s.bad.append('table outside div.tw')
            if tag == 'p' and par not in (None, ('div', 'tmpl')): s.bad.append(f'p inside {par}')
        if tag not in VOID: s.stack.append((tag, cls))
    def handle_endtag(s, tag):
        if tag in VOID: return
        if not s.stack or s.stack[-1][0] != tag: s.bad.append(f'unbalanced /{tag} stack={s.stack[-3:]}')
        else: s.stack.pop()
    def handle_data(s, d):
        if '<' in d or '>' in d: s.bad.append(f'raw angle bracket in {d[:30]!r}')

