def box(qid, items):
    rows = ''.join(f'<dt>{lab}</dt><dd>{html}</dd>' for lab, html in items)
    return (f'      <!-- PKP:{qid} -->\n      <div class="pkp"><div class="lbl">◆ 本题知识点</div><dl>{rows}</dl></div>\n'
            f'      <!-- /PKP:{qid} -->\n')


