def box(kid, items):
    rows = ''.join(f'<dt>{lab}</dt><dd>{html}</dd>' for lab, html in items)
    return (f'      <!-- KP:{kid} -->\n      <div class="kp"><div class="lbl">◆ 本题知识点</div><dl>{rows}</dl></div>\n'
            f'      <!-- /KP:{kid} -->\n')


def worked_end(s, title):
    i = s.find(title)
    if i < 0:
        raise SystemExit(f'title not found: {title}')
    j = s.rfind('<div class="worked">', 0, i)
    depth, p = 0, j
    for m in re.compile(r'<div\b|</div>').finditer(s, j):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0:
            p = m.end()
            break
    nl = s.find('\n', p)
    return len(s) if nl < 0 else nl + 1


def apply():
    n = 0
    for fn in sorted({x[0] for x in KP}):
        f = B / fn
        s = f.read_text(encoding='utf-8')
        s = re.sub(r'[ \t]*<!-- KP:(\w+) -->.*?<!-- /KP:\1 -->\n', '', s, flags=re.S)
        for _, kid, title, items in [x for x in KP if x[0] == fn]:
            i = worked_end(s, title)
            s = s[:i] + box(kid, items) + s[i:]
            n += 1
        f.write_text(s, encoding='utf-8')
    print('knowledge boxes:', n)

apply()
