#!/usr/bin/python3
"""Check that every anchor in notes.NOTES exists in the source fragments of its page.

Uses the same position() logic as inject_teacher.py. Also flags two notes sharing one anchor
(their boxes would be inserted in reverse order) and unbalanced inline tags inside items.
Run: cd src/teacher && /usr/bin/python3 _check_anchors.py
"""
import pathlib, re, sys

T = pathlib.Path(__file__).resolve().parent
REPO = T.parents[1]
P2 = REPO / 'src' / 'p2build'
sys.path.insert(0, str(T))
from notes import NOTES
from inject_teacher import position

SOURCES = {  # page key -> files whose concatenation is searched
    'p2':   [P2 / f'learn_0{i}.html' for i in range(1, 9)],
    'prac': [P2 / f'prac_{i}.html' for i in range(1, 9)],
    'B':    [P2 / f'pb_{i}.html' for i in range(1, 7)],
    'C':    [P2 / f'pc_{i}.html' for i in range(1, 7)],
    'A':    [REPO / 'partA.html'],   # hand-edited, no fragments
    'ex':   [REPO / 'exams.html'],   # generated by build_exams.py, no fragments
}

text = {}
for page, files in SOURCES.items():
    missing = [f.name for f in files if not f.exists()]
    if missing:
        print(f'WARN {page}: missing source files {missing}')
    text[page] = '\n'.join(f.read_text(encoding='utf-8') for f in files if f.exists())

bad, seen = 0, {}
for i, note in enumerate(NOTES):
    page, at = note['page'], note['at']
    if page not in text:
        print(f'FAIL note {i}: unknown page {page!r}')
        bad += 1
        continue
    if position(text[page], at) <= 0:
        print(f'FAIL note {i}: {page} anchor {at} not found')
        bad += 1
    key = (page, at)
    if key in seen:
        print(f'WARN note {i}: {page} {at} also used by note {seen[key]}')
    seen.setdefault(key, i)
    for j, item in enumerate(note['items']):
        for tag in ('b', 'mark', 'sub', 'sup', 'i'):
            if len(re.findall(rf'<{tag}[ >]', item)) != item.count(f'</{tag}>'):
                print(f'FAIL note {i} item {j}: unbalanced <{tag}>')
                bad += 1

print(f'{len(NOTES)} notes checked, {bad} failure(s)')
sys.exit(1 if bad else 0)
